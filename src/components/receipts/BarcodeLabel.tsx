/**
 * Barcode Label Component - React-based barcode label rendering
 * Based on Sultana's architecture
 */

import type { BarcodeLabel as BarcodeLabelData } from '@/services/printService';

interface Props {
  data: BarcodeLabelData;
}

export function BarcodeLabel({ data }: Props) {
  const formatPrice = (n: number) => n.toFixed(2);

  return (
    <div className="barcode-label">
      {/* Product Name */}
      <div className="barcode-label__name">{data.productName}</div>

      {/* Barcode SVG (will be generated by printService) */}
      <div className="barcode-label__barcode-container">
        <svg id="barcode"></svg>
      </div>

      {/* Barcode Number */}
      <div className="barcode-label__code">{data.barcode}</div>

      {/* Price */}
      {data.price !== undefined && (
        <div className="barcode-label__price">
          {formatPrice(data.price)} ر.س
        </div>
      )}
    </div>
  );
}
